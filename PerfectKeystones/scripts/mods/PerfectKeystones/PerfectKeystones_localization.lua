--- Perfect Keystones' DMF localization table for all twelve supported languages.
-- Returns a table from localization id to a table of texts by language code; DMF resolves
-- `mod:localize(id)` against it. Holds the mod name and description, the settings groups, every
-- setting title and tooltip and the dropdown options. The titles of the keystones and of the
-- archetype groups are built from the game's own localization with `Localize`, so they follow the
-- player's game language and match the talent tree; the English name is used when the game's text
-- cannot be read. Tooltips shared by several keystones are declared once above the table. Texts are
-- passed through `string.format` by DMF, so a literal percent sign is written as `%%`. Debug log
-- lines are developer output and stay in English.
--
-- Loaded by DMF as `mod_localization`, as declared in `PerfectKeystones.mod`.
-- module: PerfectKeystones_localization
-- author: LucLeto
local pairs = pairs
local pcall = pcall
local rawget = rawget
local string_gsub = string.gsub
local string_sub = string.sub
local type = type

--- Language codes every localization entry provides.
local LANGUAGES = {
    "en",
    "fr",
    "de",
    "it",
    "es",
    "pl",
    "pt-br",
    "ru",
    "ja",
    "ko",
    "zh-cn",
    "zh-tw"
}

--- Returns a localization entry with the same text in every language.
-- string: text text
-- treturn: tab texts by language code
local function _same_text(text)
    local localization = {}

    for i = 1, #LANGUAGES do
        localization[LANGUAGES[i]] = text
    end

    return localization
end

--- Returns a localization entry holding the game's own text for a key, in the game's current
-- language, or the English fallback when the game's localization cannot be read: before it is
-- ready it returns an empty string, and an unknown key returns an `<unlocalized ...>` message. A
-- percent sign in the game's text is doubled, as DMF passes every text through `string.format`.
-- string: key game localization key
-- string: fallback English text
-- treturn: tab texts by language code
local function _game_text(key, fallback)
    local localize = rawget(_G, "Localize")

    if type(localize) == "function" then
        local ok, text = pcall(localize, key)

        if ok and type(text) == "string" and text ~= "" and string_sub(text, 1, 1) ~= "<" then
            return _same_text((string_gsub(text, "%%", "%%%%")))
        end
    end

    return _same_text(fallback)
end

